import { Hono } from 'hono';
import { authenticateToken } from '../middleware/auth.js';

const router = new Hono();

// Apply authentication to all routes
router.use('*', authenticateToken);

// GET /api/tenants - List all tenants
router.get('/', async (c) => {
  const db = c.get('db');
  try {
    const { current_only } = c.req.query();

    let query = `
      SELECT t.*, h.house_number, h.address, h.rent_amount as current_rent
      FROM tenants t
      JOIN houses h ON t.house_id = h.id
    `;

    if (current_only === 'true') {
      query += ' WHERE t.is_current = 1';
    }

    query += ' ORDER BY t.is_current DESC, t.move_in_date DESC';

    const tenants = await db.prepare(query).all();

    return c.json(tenants);
  } catch (error) {
    console.error('Error fetching tenants:', error);
    return c.json({ error: 'Failed to fetch tenants' }, 500);
  }
});

// GET /api/tenants/:id - Get tenant details with payment history
router.get('/:id', async (c) => {
  const db = c.get('db');
  try {
    const tenant = await db.prepare(`
      SELECT t.*, h.house_number, h.address, h.rent_amount as current_rent
      FROM tenants t
      JOIN houses h ON t.house_id = h.id
      WHERE t.id = ?
    `).get(c.req.param('id'));

    if (!tenant) {
      return c.json({ error: 'Tenant not found' }, 404);
    }

    // Get payment history
    const payments = await db.prepare(`
      SELECT rp.*,
        (SELECT json_group_array(json_object('id', ra.id, 'source_type', ra.source_type, 'amount', ra.amount, 'description', ra.description))
         FROM rent_additions ra WHERE ra.rent_payment_id = rp.id) as additions
      FROM rent_payments rp
      WHERE rp.tenant_id = ?
      ORDER BY rp.due_date DESC
    `).all(c.req.param('id'));

    // Parse additions JSON
    payments.forEach(p => {
      p.additions = JSON.parse(p.additions || '[]');
    });

    // Calculate total pending
    const pendingResult = await db.prepare(`
      SELECT SUM(due_amount - paid_amount) as total_pending
      FROM rent_payments
      WHERE tenant_id = ? AND is_fully_paid = 0
    `).get(c.req.param('id'));

    return c.json({
      ...tenant,
      payments,
      totalPending: pendingResult?.total_pending || 0
    });
  } catch (error) {
    console.error('Error fetching tenant:', error);
    return c.json({ error: 'Failed to fetch tenant' }, 500);
  }
});

// POST /api/tenants - Add new tenant
router.post('/', async (c) => {
  const db = c.get('db');
  try {
    const {
      house_id,
      name,
      phone,
      id_proof_number,
      occupation,
      household_members,
      move_in_date,
      advance_amount,
      advance_date
    } = await c.req.json().catch(() => ({}));

    if (!house_id || !name || !move_in_date) {
      return c.json({ error: 'House ID, name, and move-in date are required' }, 400);
    }

    // Check if house exists and is active
    const house = await db.prepare('SELECT * FROM houses WHERE id = ? AND is_active = 1').get(house_id);

    if (!house) {
      return c.json({ error: 'House not found' }, 404);
    }

    // Check if house already has a current tenant
    const existingTenant = await db.prepare('SELECT * FROM tenants WHERE house_id = ? AND is_current = 1').get(house_id);

    if (existingTenant) {
      return c.json({ error: 'House already has a current tenant. Move out the existing tenant first.' }, 400);
    }

    const result = await db.prepare(`
      INSERT INTO tenants (house_id, name, phone, id_proof_number, occupation, household_members, move_in_date, advance_amount, advance_date)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(house_id, name, phone, id_proof_number, occupation, household_members, move_in_date, advance_amount, advance_date);

    const newTenant = await db.prepare(`
      SELECT t.*, h.house_number
      FROM tenants t
      JOIN houses h ON t.house_id = h.id
      WHERE t.id = ?
    `).get(result.lastInsertRowid);

    // Rent will be automatically generated by the scheduler on the 1st of each month
    // No manual rent creation here

    return c.json(newTenant, 201);
  } catch (error) {
    console.error('Error creating tenant:', error);
    return c.json({ error: 'Failed to create tenant' }, 500);
  }
});

// PUT /api/tenants/:id - Update tenant
router.put('/:id', async (c) => {
  const db = c.get('db');
  try {
    const {
      name,
      phone,
      id_proof_number,
      occupation,
      household_members,
      advance_amount,
      advance_date
    } = await c.req.json().catch(() => ({}));

    const existingTenant = await db.prepare('SELECT * FROM tenants WHERE id = ?').get(c.req.param('id'));

    if (!existingTenant) {
      return c.json({ error: 'Tenant not found' }, 404);
    }

    await db.prepare(`
      UPDATE tenants
      SET name = ?, phone = ?, id_proof_number = ?, occupation = ?, household_members = ?, advance_amount = ?, advance_date = ?
      WHERE id = ?
    `).run(
      name || existingTenant.name,
      phone ?? existingTenant.phone,
      id_proof_number ?? existingTenant.id_proof_number,
      occupation ?? existingTenant.occupation,
      household_members ?? existingTenant.household_members,
      advance_amount ?? existingTenant.advance_amount,
      advance_date ?? existingTenant.advance_date,
      c.req.param('id')
    );

    const updatedTenant = await db.prepare(`
      SELECT t.*, h.house_number
      FROM tenants t
      JOIN houses h ON t.house_id = h.id
      WHERE t.id = ?
    `).get(c.req.param('id'));

    return c.json(updatedTenant);
  } catch (error) {
    console.error('Error updating tenant:', error);
    return c.json({ error: 'Failed to update tenant' }, 500);
  }
});

// DELETE /api/tenants/:id - Permanently delete tenant and all records
router.delete('/:id', async (c) => {
  const db = c.get('db');
  try {
    const tenant = await db.prepare('SELECT * FROM tenants WHERE id = ?').get(c.req.param('id'));

    if (!tenant) {
      return c.json({ error: 'Tenant not found' }, 404);
    }

    // Delete in order: rent_additions -> rent_payments -> tenant
    // First get all rent payment IDs for this tenant
    const paymentIds = await db.prepare('SELECT id FROM rent_payments WHERE tenant_id = ?').all(c.req.param('id'));

    // Delete rent additions for these payments
    for (const payment of paymentIds) {
      await db.prepare('DELETE FROM rent_additions WHERE rent_payment_id = ?').run(payment.id);
    }

    // Delete rent payments
    await db.prepare('DELETE FROM rent_payments WHERE tenant_id = ?').run(c.req.param('id'));

    // Delete tenant
    await db.prepare('DELETE FROM tenants WHERE id = ?').run(c.req.param('id'));

    return c.json({ message: 'Tenant and all related records permanently deleted' });
  } catch (error) {
    console.error('Error deleting tenant:', error);
    return c.json({ error: 'Failed to delete tenant' }, 500);
  }
});

// PUT /api/tenants/:id/move-out - Mark tenant as moved out
router.put('/:id/move-out', async (c) => {
  const db = c.get('db');
  try {
    const { move_out_date } = await c.req.json().catch(() => ({}));

    if (!move_out_date) {
      return c.json({ error: 'Move-out date is required' }, 400);
    }

    const existingTenant = await db.prepare('SELECT * FROM tenants WHERE id = ? AND is_current = 1').get(c.req.param('id'));

    if (!existingTenant) {
      return c.json({ error: 'Current tenant not found' }, 404);
    }

    // Check for pending payments
    const pendingPayments = await db.prepare(`
      SELECT SUM(due_amount - paid_amount) as total_pending
      FROM rent_payments
      WHERE tenant_id = ? AND is_fully_paid = 0
    `).get(c.req.param('id'));

    await db.prepare(`
      UPDATE tenants
      SET is_current = 0, move_out_date = ?
      WHERE id = ?
    `).run(move_out_date, c.req.param('id'));

    const updatedTenant = await db.prepare(`
      SELECT t.*, h.house_number
      FROM tenants t
      JOIN houses h ON t.house_id = h.id
      WHERE t.id = ?
    `).get(c.req.param('id'));

    return c.json({
      ...updatedTenant,
      pendingAmount: pendingPayments?.total_pending || 0,
      message: pendingPayments?.total_pending > 0 ? 'Tenant moved out with pending payments' : 'Tenant moved out successfully'
    });
  } catch (error) {
    console.error('Error moving out tenant:', error);
    return c.json({ error: 'Failed to move out tenant' }, 500);
  }
});

export default router;
